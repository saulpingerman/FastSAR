_SRC = r'''
#include <cuda_fp16.h>
#if STORE == 16
  typedef __half sample_t;           /* phase history, intermediates and outputs in memory */
  #define LD(v) __half2float(v)
  #define ST(v) __float2half(v)
#else
  typedef float sample_t;
  #define LD(v) (v)
  #define ST(v) (v)
#endif
#ifndef COLB
#define COLB 1         /* final_tile builds its tables by columns (0: by rows, as in 0.1.2) */
#endif
#ifndef PB
#define PB 32          /* pulses per block in rot_fir_k (16 or 8 when a wide window would overflow shared memory) */
#endif
#ifndef JT
#define JT 8           /* threads per pulse, each two consecutive outputs: 2 JT columns per block */
#endif
extern "C" __global__
void rot_fir_k(const sample_t* __restrict__ sre, const sample_t* __restrict__ sim, const float* __restrict__ c0, const float* __restrict__ sl,
               const float* __restrict__ taps, sample_t* __restrict__ yre, sample_t* __restrict__ yim,
               int C_, int P, int K, int Ko, int D, int L, int pl, float kc)
{
    // grid: x = blocks of 2 JT output columns, y = blocks of PB pulses, z = parent; block = PB * JT threads
    // thread (pp, jt): pulse p0 + pp, outputs j0 + 2 jt and j0 + 2 jt + 1. Consecutive threads are consecutive
    // pulses, so shared-memory rows (odd stride) are read without bank conflicts.
    const int j0 = blockIdx.x * (2 * JT), p0 = blockIdx.y * PB, n = blockIdx.z, tid = threadIdx.x;
    const int pp = tid % PB, jt = tid / PB;
    const int W = 2 * JT * D + L;                       // window per pulse
    const int WS = W | 1;                               // odd row stride
    const int kstart = D * j0 - pl;
    extern __shared__ float sm[];
    float* zr = sm; float* zi = sm + PB * WS; float* tp = sm + 2 * PB * WS;
    float* otr = tp + L; float* oti = otr + PB * 2 * JT;   // output tile [PB][2 JT], written out row-contiguous
    for (int r = tid; r < L; r += PB * JT) tp[r] = taps[r];
    const int p = p0 + pp;
    const bool pok = p < P;
    const int j = j0 + 2 * jt;
    // the raw window, loaded once with consecutive threads on consecutive columns (coalesced)
    for (int idx = tid; idx < PB * W; idx += PB * JT) {
        const int row = idx / W, i = idx % W, k = kstart + i, pr = p0 + row;
        const bool ok = (pr < P) && (k >= 0) && (k < K);
        zr[row * WS + i] = ok ? LD(sre[((size_t)n * P + pr) * K + k]) : 0.f;
        zi[row * WS + i] = ok ? LD(sim[((size_t)n * P + pr) * K + k]) : 0.f;
    }
    __syncthreads();
    float prev_cc = 0.f, prev_ss = 0.f;
    for (int c = 0; c < C_; ++c) {
        // rotate the window in place by the ramp of child c relative to child c - 1 (one sine and cosine per sample
        // and child, as before, but no second copy of the window); threads along columns, so the rows differ per
        // warp only through the ramp coefficients
        const float cc = pok ? c0[((size_t)n * C_ + c) * P + p] : 0.f;
        const float ss = pok ? sl[((size_t)n * C_ + c) * P + p] : 0.f;
        {
            // this thread's samples are JT columns apart, so their phase steps are constant: one sine and cosine for
            // the first sample and one for the step, then a complex multiplication per sample (a geometric sequence)
            const float dcc = cc - prev_cc, dss = ss - prev_ss;
            float cyc = dcc + ((float)(kstart + jt) - kc) * dss;
            cyc -= rintf(cyc);
            float st = (float)JT * dss;
            st -= rintf(st);
            float wi_, wr_, si_, sr_;
            sincospif(2.0f * cyc, &wi_, &wr_);
            sincospif(2.0f * st, &si_, &sr_);
            for (int i = jt; i < W; i += JT) {
                const float vr = zr[pp * WS + i], vi = zi[pp * WS + i];
                zr[pp * WS + i] = vr * wr_ - vi * wi_;
                zi[pp * WS + i] = vr * wi_ + vi * wr_;
                const float nr = wr_ * sr_ - wi_ * si_;
                wi_ = wr_ * si_ + wi_ * sr_; wr_ = nr;
            }
            prev_cc = cc; prev_ss = ss;
        }
        __syncthreads();
        {
            float a0r = 0.f, a0i = 0.f, a1r = 0.f, a1i = 0.f;
            const float* row_r = zr + pp * WS + 2 * jt * D;
            const float* row_i = zi + pp * WS + 2 * jt * D;
            for (int r = 0; r < D; ++r) {                 // taps only the first output uses
                const float t = tp[r];
                a0r = fmaf(t, row_r[r], a0r); a0i = fmaf(t, row_i[r], a0i);
            }
            for (int r = D; r < L; ++r) {                 // shared samples
                const float vr = row_r[r], vi = row_i[r];
                const float t0 = tp[r], t1 = tp[r - D];
                a0r = fmaf(t0, vr, a0r); a0i = fmaf(t0, vi, a0i);
                a1r = fmaf(t1, vr, a1r); a1i = fmaf(t1, vi, a1i);
            }
            for (int r = L; r < L + D; ++r) {             // taps only the second output uses
                const float t = tp[r - D];
                a1r = fmaf(t, row_r[r], a1r); a1i = fmaf(t, row_i[r], a1i);
            }
            otr[pp * (2 * JT) + 2 * jt] = a0r; oti[pp * (2 * JT) + 2 * jt] = a0i;
            otr[pp * (2 * JT) + 2 * jt + 1] = a1r; oti[pp * (2 * JT) + 2 * jt + 1] = a1i;
        }
        __syncthreads();
        // coalesced store: consecutive threads write consecutive columns of one pulse's row
        for (int idx = tid; idx < PB * 2 * JT; idx += PB * JT) {
            const int row = idx / (2 * JT), col = idx % (2 * JT), pr = p0 + row, jj = j0 + col;
            if (pr < P && jj < Ko) {
                const size_t o = (((size_t)n * C_ + c) * P + pr) * (size_t)Ko + jj;
                yre[o] = ST(otr[idx]); yim[o] = ST(oti[idx]);
            }
        }
        __syncthreads();
    }
}

#define FP_COLS 64     /* columns per block in fir_p */
extern "C" __global__
void fir_p(const sample_t* __restrict__ yre, const sample_t* __restrict__ yim, const float* __restrict__ taps,
           sample_t* __restrict__ zre, sample_t* __restrict__ zim, int P, int Ko, int Po, int D, int L, int pl, int nout)
{
    // grid: x = blocks of FP_COLS columns, y = blocks of nout output pulses, z = child; block = FP_COLS * 4 threads,
    // each thread nout / 4 of the outputs of its column. The input rows the block needs sit in shared memory
    // (nout is chosen by the caller so that they fit).
    const int j = blockIdx.x * FP_COLS + threadIdx.x % FP_COLS, i0 = blockIdx.y * nout, b = blockIdx.z, q = threadIdx.x / FP_COLS;
    const int rows = (nout - 1) * D + L;
    extern __shared__ float sm[];
    float* tr_ = sm; float* ti_ = sm + rows * FP_COLS; float* tp = sm + 2 * rows * FP_COLS;
    const sample_t* yr = yre + (size_t)b * P * Ko;
    const sample_t* yi = yim + (size_t)b * P * Ko;
    const int pstart = D * i0 - pl;
    for (int r = q; r < rows; r += 4) {
        const int p = pstart + r;
        const bool ok = (p >= 0) && (p < P) && (j < Ko);
        tr_[r * FP_COLS + threadIdx.x % FP_COLS] = ok ? LD(yr[(size_t)p * Ko + j]) : 0.f;
        ti_[r * FP_COLS + threadIdx.x % FP_COLS] = ok ? LD(yi[(size_t)p * Ko + j]) : 0.f;
    }
    for (int r = threadIdx.x; r < L; r += FP_COLS * 4) tp[r] = taps[r];
    __syncthreads();
    if (j >= Ko) return;
    const int col = threadIdx.x % FP_COLS;
    for (int m = 0; m < nout / 4; ++m) {
        const int io = q * (nout / 4) + m;                // local output index
        const int i = i0 + io;
        if (i >= Po) break;
        float ar = 0.f, ai = 0.f;
        const float* cr = tr_ + (io * D) * FP_COLS + col;
        const float* ci = ti_ + (io * D) * FP_COLS + col;
        for (int r = 0; r < L; ++r) {
            const float t = tp[r];
            ar = fmaf(t, cr[r * FP_COLS], ar);
            ai = fmaf(t, ci[r * FP_COLS], ai);
        }
        const size_t o = ((size_t)b * Po + i) * (size_t)Ko + j;
        zre[o] = ST(ar); zim[o] = ST(ai);
    }
}

extern "C" __global__
void fir_p_g(const sample_t* __restrict__ yre, const sample_t* __restrict__ yim, const float* __restrict__ taps,
             sample_t* __restrict__ zre, sample_t* __restrict__ zim, int P, int Ko, int Po, int D, int L, int pl, int nout)
{
    // fir_p for decimation factors whose input rows do not fit in shared memory: the same sums, read from global memory
    const int j = blockIdx.x * FP_COLS + threadIdx.x % FP_COLS, i0 = blockIdx.y * nout, b = blockIdx.z, q = threadIdx.x / FP_COLS;
    if (j >= Ko) return;
    const sample_t* yr = yre + (size_t)b * P * Ko;
    const sample_t* yi = yim + (size_t)b * P * Ko;
    for (int m = 0; m < nout / 4; ++m) {
        const int i = i0 + q * (nout / 4) + m;
        if (i >= Po) break;
        const int p0 = D * i - pl;
        float ar = 0.f, ai = 0.f;
        for (int r = max(0, -p0); r < L && p0 + r < P; ++r) {
            const float t = taps[r];
            const size_t o = (size_t)(p0 + r) * Ko + j;
            ar = fmaf(t, LD(yr[o]), ar);
            ai = fmaf(t, LD(yi[o]), ai);
        }
        const size_t o = ((size_t)b * Po + i) * (size_t)Ko + j;
        zre[o] = ST(ar); zim[o] = ST(ai);
    }
}

extern "C" __global__
void final_tile(const sample_t* __restrict__ dre, const sample_t* __restrict__ dim, const float* __restrict__ ux, const float* __restrict__ uy,
                const float* __restrict__ dlx, const float* __restrict__ dly, float* __restrict__ ore, float* __restrict__ oim,
                int Pf, int Qf, int T, float a0, float a1, int pps, const float* __restrict__ w0, const float* __restrict__ gx,
                const float* __restrict__ gyr, int has_w)
{
    // grid: x = tile; block = T * T / 8 threads, each a 4 (x) by 2 (y) block of pixels. Tables for pps pulses per sync.
    // has_w: an aperture weight per subaperture and pixel, w0 + gx dx + gy dy, applied as (w0 + gx dx)(1 + gyr dy) with
    // gyr = gy / w0 ([B, Pf] each): the x factor on the data table A, the y factor on table B
    const int b = blockIdx.x, tid = threadIdx.x, HX = T / 4, tx = tid % HX, ty = tid / HX;
    extern __shared__ float2 sm2[];
    const int rowlen = pps * Qf;                          // pps pulses side by side
    const int ld = rowlen;                                // row stride (a padded stride against bank conflicts gained nothing)
    float2* A2 = sm2; float2* B2 = sm2 + T * ld;          // (re, im) pairs: one 8-byte load per complex table entry
    const sample_t* dr = dre + (size_t)b * Pf * Qf;
    const sample_t* di = dim + (size_t)b * Pf * Qf;
    float acc_r[4][2], acc_i[4][2];
    #pragma unroll
    for (int u = 0; u < 4; ++u) { acc_r[u][0] = acc_r[u][1] = acc_i[u][0] = acc_i[u][1] = 0.f; }
    const int nthr = (T * T) / 8;
    const int nseg = nthr / (2 * T);                      // threads per table row
    const int row = tid / nseg, seg = tid % nseg;
    const int qlen = (rowlen + nseg - 1) / nseg;
    const int qa = seg * qlen, qb = min(rowlen, qa + qlen);
    for (int p0 = 0; p0 < Pf; p0 += pps) {
#if COLB
        {
            // the tables by columns, as in final_tile_tc2: the phase of sample q of pulse p is linear in the pixel
            // offset, so a walk along the rows costs one complex multiply per entry and loads the sample once
            const int units = 2 * 2 * pps * Qf;                         // two tables, two row groups per column
            const float stepx = (dlx[T - 1] - dlx[0]) * (1.0f / (float)(T - 1));
            const float stepy = (dly[T - 1] - dly[0]) * (1.0f / (float)(T - 1));
            for (int u = tid; u < units; u += nthr) {
                const int qq = u % Qf; int r = u / Qf;
                const int ph = r % pps; r /= pps;
                const int h = r % 2; const bool isA = (r / 2) == 0;
                const int p = p0 + ph;
                const bool pok = p < Pf;
                const float* dl = isA ? dlx : dly;
                const float c = pok ? (isA ? ux[b * Pf + p] : uy[b * Pf + p]) * (a0 + a1 * (float)qq) : 0.f;
                const int rows = T / 2, tr0 = h * rows;
                float f0 = -(c * dl[tr0]); f0 -= rintf(f0);
                float fs = -(c * (isA ? stepx : stepy)); fs -= rintf(fs);
                float wr, wi, sr, si_;
                sincospif(2.0f * f0, &wi, &wr);
                sincospif(2.0f * fs, &si_, &sr);
                float vr = wr, vi = wi;
                if (isA) {
                    const float d_r = pok ? LD(dr[p * Qf + qq]) : 0.f, d_i = pok ? LD(di[p * Qf + qq]) : 0.f;
                    vr = d_r * wr - d_i * wi; vi = d_r * wi + d_i * wr;
                }
                float2* col = (isA ? A2 : B2) + ph * Qf + qq;
                const size_t bp = (size_t)b * Pf + p;
                for (int tr = tr0; tr < tr0 + rows; ++tr) {
                    float lw = 1.f;
                    if (has_w && pok) lw = isA ? w0[bp] + gx[bp] * dlx[tr] : 1.f + gyr[bp] * dly[tr];
                    col[tr * ld] = make_float2(vr * lw, vi * lw);
                    const float nr = vr * sr - vi * si_;
                    vi = vr * si_ + vi * sr; vr = nr;
                }
            }
        }
#else
        {
            const bool isA = row < T;
            const int tr = isA ? row : row - T;
            float2* R2 = (isA ? A2 : B2) + tr * ld;
            // segment [qa, qb) of the row: entries q < Qf belong to pulse p0, the rest to the following pulses
            int q = qa;
            while (q < qb) {
                const int ph = q / Qf, p = p0 + ph, qq = q - ph * Qf;
                const int qend = min(qb, (ph + 1) * Qf);
                const bool pok = p < Pf;
                const float g = pok ? (isA ? ux[b * Pf + p] * dlx[tr] : uy[b * Pf + p] * dly[tr]) : 0.f;
                float cyc0 = -(g * (a0 + a1 * (float)qq)); cyc0 -= rintf(cyc0);
                float cs = -(g * a1); cs -= rintf(cs);
                float wr, wi, sr, si_;
                sincospif(2.0f * cyc0, &wi, &wr);
                sincospif(2.0f * cs, &si_, &sr);
                float lw = 1.f;
                if (has_w && pok) {
                    const size_t bp = (size_t)b * Pf + p;
                    lw = isA ? w0[bp] + gx[bp] * dlx[tr] : 1.f + gyr[bp] * dly[tr];
                }
                for (; q < qend; ++q) {
                    const int qq2 = q - ph * Qf;
                    if (isA) {
                        const float d_r = pok ? LD(dr[p * Qf + qq2]) * lw : 0.f, d_i = pok ? LD(di[p * Qf + qq2]) * lw : 0.f;
                        R2[q] = make_float2(d_r * wr - d_i * wi, d_r * wi + d_i * wr);
                    } else {
                        R2[q] = make_float2(wr * lw, wi * lw);
                    }
                    const float nr = wr * sr - wi * si_;
                    wi = wr * si_ + wi * sr; wr = nr;
                }
            }
        }
#endif
        __syncthreads();
        const float2* a0 = A2 + (4 * tx) * ld;
        const float2* b0 = B2 + (2 * ty) * ld;
        #pragma unroll 2
        for (int q = 0; q < rowlen; ++q) {
            const float2 y0 = b0[q], y1 = b0[ld + q];
            const float y0r = y0.x, y0i = y0.y, y1r = y1.x, y1i = y1.y;
            #pragma unroll
            for (int u = 0; u < 4; ++u) {
                const float2 x = a0[u * ld + q];
                const float xr = x.x, xi = x.y;
                acc_r[u][0] = fmaf(xr, y0r, acc_r[u][0]); acc_r[u][0] = fmaf(-xi, y0i, acc_r[u][0]);
                acc_i[u][0] = fmaf(xr, y0i, acc_i[u][0]); acc_i[u][0] = fmaf(xi, y0r, acc_i[u][0]);
                acc_r[u][1] = fmaf(xr, y1r, acc_r[u][1]); acc_r[u][1] = fmaf(-xi, y1i, acc_r[u][1]);
                acc_i[u][1] = fmaf(xr, y1i, acc_i[u][1]); acc_i[u][1] = fmaf(xi, y1r, acc_i[u][1]);
            }
        }
        __syncthreads();
    }
    #pragma unroll
    for (int u = 0; u < 4; ++u) {
        const size_t o = ((size_t)b * T + 4 * tx + u) * T + 2 * ty;
        ore[o] = acc_r[u][0]; oim[o] = acc_i[u][0]; ore[o + 1] = acc_r[u][1]; oim[o + 1] = acc_i[u][1];
    }
}
'''

_mods = {}
_PB_CHOICES = (32, 16, 8)        # pulses per block tried in order by the level kernel (tests may narrow this)


def _kernels(store='fp32', pb=32):
    bits = 16 if store == 'f16' else 32
    jt = int(os.environ.get('FASTSAR_CUDA_JT', 0) or 0) or 8          # threads per pulse in rot_fir_k (testing)
    colb = int(os.environ.get('FASTSAR_FINAL_COLB', '1'))             # final_tile's table build by columns (testing)
    key = (bits, pb, jt, colb)
    if key not in _mods:
        _mods[key] = cp.RawModule(code=_SRC, options=('--std=c++14', '--use_fast_math', f'-DSTORE={bits}', f'-DPB={pb}', f'-DJT={jt}', f'-DCOLB={colb}'))
    out = {k: _mods[key].get_function(k) for k in ('rot_fir_k', 'fir_p', 'fir_p_g', 'final_tile')}
    # opt in once to the device's largest shared memory per block: the limit belongs to the kernel, which every former
    # shares, so a former must never lower it (a former built on another thread while one runs would break its launch)
    smax = int(cp.cuda.Device().attributes.get('MaxSharedMemoryPerBlockOptin', 96 * 1024))
    for k in out.values():
        k.max_dynamic_shared_size_bytes = smax
    out['dtype'] = cp.float16 if bits == 16 else cp.float32
    out['store'] = store
    out['jt'] = jt
    return out


_TAPS = {}


def _dev_taps(kern_h):
    """A filter's taps on the device, uploaded once (a copy from the host makes the host wait for the GPU)."""
    key = (id(kern_h), len(kern_h))
    t = _TAPS.get(key)
    if t is None or t[0] is not kern_h:
        if len(_TAPS) > 256:
            _TAPS.clear()
        t = _TAPS[key] = (kern_h, cp.asarray(kern_h, cp.float32))
    return t[1]


def _children(kern, pre, pim, c0, sl, lv):
    """pre, pim [Np, P, K] float32 (device); c0, sl [Np, C, P] float32 (device) -> [Np C, Po, Ko] planes."""
    Np, P, K = pre.shape
    Cn, Ko, Po, Dk, Dp = c0.shape[1], lv['Ko'], lv['Po'], lv['Dk'], lv['Dp']
    kc = (K - 1) / 2.0
    t0 = _tick()
    if Dk > 1:
        fk = lv['fir_k']
        taps = _dev_taps(fk['kern'])
        L, pl = fk['L'], fk['pl']
        yre = cp.empty((Np * Cn, P, Ko), kern['dtype'])
        yim = cp.empty((Np * Cn, P, Ko), kern['dtype'])
        jt = kern['jt']
        cols = 2 * jt                                     # output columns per block
        W = cols * Dk + L
        smem_max = int(cp.cuda.Device().attributes.get('MaxSharedMemoryPerBlockOptin', 48 * 1024))
        pb_env = int(os.environ.get('FASTSAR_CUDA_PB', 0) or 0)           # testing: force the pulses per block
        for pb in ((pb_env,) if pb_env else _PB_CHOICES):   # pulses per block: the largest whose window fits the device
            smem = (2 * pb * (W | 1) + L + 2 * pb * cols) * 4
            if smem <= smem_max:
                break
        if smem > smem_max:
            raise ValueError(f"the cuda backend's first-level window ({smem // 1024} KB: range decimation {Dk} with a "
                             f"{L}-tap filter, a small image from a wide-band collection) exceeds the GPU's shared memory "
                             f"({smem_max // 1024} KB): use backend='cpu' or 'jax', or a larger image")
        kl = kern['rot_fir_k'] if pb == 32 else _kernels(kern['store'], pb)['rot_fir_k']
        kl(((Ko + cols - 1) // cols, (P + pb - 1) // pb, Np), (pb * jt,),
                          (pre, pim, c0, sl, taps, yre, yim, np.int32(Cn), np.int32(P), np.int32(K), np.int32(Ko), np.int32(Dk),
                           np.int32(L), np.int32(pl), np.float32(kc)), shared_mem=smem)
    else:
        # no frequency decimation at this level: rotate only (rare; D = 1 keeps the matrix the identity)
        k = cp.arange(K, dtype=cp.float32) - np.float32(kc)
        cyc = c0[:, :, :, None] + k[None, None, None, :] * sl[:, :, :, None]
        ang = (cyc - cp.rint(cyc)) * (2 * np.pi)
        cs, sn = cp.cos(ang), cp.sin(ang)
        yre = (pre[:, None] * cs - pim[:, None] * sn).reshape(Np * Cn, P, K).astype(kern['dtype'])
        yim = (pre[:, None] * sn + pim[:, None] * cs).reshape(Np * Cn, P, K).astype(kern['dtype'])
    _mark('rot_fir_k', t0)
    t0 = _tick()
    if Dp > 1:
        fp = lv['fir_p']
        taps = _dev_taps(fp['kern'])
        zre = cp.empty((Np * Cn, Po, Ko), kern['dtype'])
        zim = cp.empty((Np * Cn, Po, Ko), kern['dtype'])
        # outputs per block: as many as keep the input rows within 40 KB of shared memory (FASTSAR_FIRP_SMEM, in KB,
        # overrides for testing; larger budgets were slower on the H100 and the L4, the kernel wants blocks in flight)
        budget = (int(os.environ.get('FASTSAR_FIRP_SMEM', 0) or 0) or 40) * 1024
        nout = 64
        while nout > 4 and (2 * ((nout - 1) * Dp + fp['L']) * 64 + fp['L']) * 4 > budget:      # a multiple of 4
            nout -= 4
        rows = (nout - 1) * Dp + fp['L']
        smem = (2 * rows * 64 + fp['L']) * 4
        name = 'fir_p'
        # the rows through shared memory, or straight from global memory with the cache serving their reuse: the
        # latter was faster on the A100 and H100 (0.14 against 0.16 s and 0.07 against 0.09 s on Panama) and slower
        # on the L4, so cards with at least 100 streaming multiprocessors take it; FASTSAR_FIRP=smem|global overrides
        attrs = cp.cuda.Device().attributes
        mode = os.environ.get('FASTSAR_FIRP') or ('global' if os.environ.get('FASTSAR_FIRP_GLOBAL') or attrs.get('MultiProcessorCount', 0) >= 100 else 'smem')
        if mode == 'global' or smem > int(attrs.get('MaxSharedMemoryPerBlockOptin', 96 * 1024)):
            name, smem = 'fir_p_g', 0           # (also beyond what the kernels opted in to in _kernels)
        kern[name](((Ko + 63) // 64, (Po + nout - 1) // nout, Np * Cn), (256,),
                   (yre, yim, taps, zre, zim, np.int32(P), np.int32(Ko), np.int32(Po), np.int32(Dp), np.int32(fp['L']), np.int32(fp['pl']), np.int32(nout)),
                   shared_mem=smem)
        _mark('fir_p', t0)
        return zre, zim
    return yre, yim



_PHASES_KERN = None


def _device_phases(la, refs, lv):
    """Band-center phase and slope of every child of every parent (float64 on the device): refs [Np, 3] ->
    c0, slope [Np, C, P] float32. Same formula as ffbp2.device_phases, in one fused kernel (the dozen separate
    array operations it replaces cost a mosaic about 2 ms of host time per call)."""
    global _PHASES_KERN
    k0c = 2.0 * (lv['f0'] + (lv['K'] - 1) / 2.0 * lv['df']) / C
    k1 = 2.0 * lv['df'] / C
    u, r0, d = la['u'], la['r0'], la['d']                                   # [P, 3], [P], [C, 3] float64 device
    Np, Cn, P = refs.shape[0], d.shape[0], u.shape[0]
    if _PHASES_KERN is None:
        _PHASES_KERN = cp.ElementwiseKernel(
            'raw float64 refs, raw float64 u, raw float64 r0, raw float64 d, int32 Cn, int32 P, float64 k0c, float64 k1',
            'float32 c0, float32 sl',
            '''
            const int p = i % P; const int c = (i / P) % Cn; const int n = i / (P * Cn);
            const double rx = refs[3 * n], ry = refs[3 * n + 1], rz = refs[3 * n + 2];
            const double ux = u[3 * p], uy = u[3 * p + 1], uz = u[3 * p + 2];
            const double dx = d[3 * c], dy = d[3 * c + 1], dz = d[3 * c + 2];
            const double r = r0[p];
            const double uc = rx * ux + ry * uy + rz * uz;
            const double rr = rx * rx + ry * ry + rz * rz;
            const double wn = r * sqrt(1.0 + (rr - 2.0 * r * uc) / (r * r));
            const double ud = dx * ux + dy * uy + dz * uz;
            const double wd = r * ud - (dx * rx + dy * ry + dz * rz);
            const double num = (dx * dx + dy * dy + dz * dz) - 2.0 * wd;
            const double ddr = num / (sqrt(wn * wn + num) + wn);
            const double cc = ddr * k0c;
            c0 = (float)(cc - rint(cc));
            sl = (float)(ddr * k1);
            ''', 'fastsar_device_phases')
    c0 = cp.empty((Np, Cn, P), cp.float32)
    sl = cp.empty((Np, Cn, P), cp.float32)
    _PHASES_KERN(cp.ascontiguousarray(refs, cp.float64), cp.ascontiguousarray(u, cp.float64), cp.ascontiguousarray(r0, cp.float64),
                 cp.ascontiguousarray(d, cp.float64), np.int32(Cn), np.int32(P), np.float64(k0c), np.float64(k1), c0, sl)
    return c0, sl


PROFILE = {}


def _mark(name, start):
    """Accumulate the device time since `start` (an Event) under `name` when profiling is on."""
    if PROFILE.get('on'):
        e = cp.cuda.Event()
        e.record()
        e.synchronize()
        PROFILE[name] = PROFILE.get(name, 0.0) + cp.cuda.get_elapsed_time(start, e) * 1e-3


def _tick():
    if PROFILE.get('on'):
        e = cp.cuda.Event()
        e.record()
        return e
    return None


def _copy_rows(dst, src, nth):
    """dst[...] = src by row slices on nth threads (NumPy releases the GIL in the copy, so the threads add up)."""
    if nth <= 1 or dst.shape[0] < 64:
        np.copyto(dst, src)
        return
    import threading
    rows = dst.shape[0]
    ths = []
    for q in range(nth):
        a, b = rows * q // nth, rows * (q + 1) // nth
        th = threading.Thread(target=np.copyto, args=(dst[a:b], src[a:b]))
        th.start()
        ths.append(th)
    for th in ths:
        th.join()


def _upload_planes(S, pre, pim, win, check, scaled):
    """Host S [P, K] complex -> float planes pre, pim [P, K] on the device, in row blocks through two pinned staging
    buffers: the threads copying the next block into its buffer overlap the transfer of the current one, and the
    blocks are windowed (win: device [P, 1] and [1, K] windows, or None), checked and converted on the device.
    scaled: float16 planes, divided by the first block's peak, a reference scale for the half range (the relative
    precision of float16 does not depend on where in its range the data sit). Returns the scale."""
    P, K = S.shape
    nb = memory.STREAM_PULSES
    rows = min(nb, P)
    bufs = [cp.cuda.alloc_pinned_memory(rows * K * 8) for _ in range(2)]          # pooled: reused by later calls
    stg = [np.frombuffer(b, np.complex64, rows * K).reshape(rows, K) for b in bufs]
    st = cp.cuda.Stream(non_blocking=True)
    done = [None, None]
    nth = max(1, min(8, (os.cpu_count() or 2) - 1))
    scale = 1.0
    sums = []
    with st:
        for n, i in enumerate(range(0, P, nb)):
            r, k = min(nb, P - i), n % 2
            if done[k] is not None:
                done[k].synchronize()                                             # the buffer's last transfer is complete
            _copy_rows(stg[k][:r], S[i:i + r], nth)
            b = cp.asarray(stg[k][:r])                                            # asynchronous from pinned memory
            e = cp.cuda.Event()
            e.record(st)
            done[k] = e
            if win is not None:
                b = b * win[0][i:i + r] * win[1]
            if check:
                sums.append(b.sum())                                              # checked once at the end (no sync here)
            if scaled and n == 0:
                scale = float(cp.abs(b).max()) or 1.0
            pre[i:i + r] = (b.real / scale).astype(pre.dtype) if scale != 1.0 else b.real.astype(pre.dtype)
            pim[i:i + r] = (b.imag / scale).astype(pim.dtype) if scale != 1.0 else b.imag.astype(pim.dtype)
            del b
    st.synchronize()
    if check and not np.isfinite(complex(cp.stack(sums).sum())):
        for n, i in enumerate(range(0, P, nb)):
            if not np.isfinite(complex(sums[n])):
                r = min(nb, P - i)
                bad = i + int(cp.argmax((~cp.isfinite(pre[i:i + r])).any(1) | (~cp.isfinite(pim[i:i + r])).any(1)))
                raise ValueError(f'phase history has non-finite samples (NaN or inf), the first in pulse {bad}; '
                                 'zero them (S[~np.isfinite(S)] = 0) or drop the pulses')
    return scale


_GEOM_KERN = None


def _final_geom_kernel():
    """[B, Pf] unit-vector components (along e1, e2, their normal) and lengths of the vectors from the tile centers
    cen [B, 3] to the final subapertures' antenna positions r0 u (fu [Pf, 3], fr0 [Pf]), one fused kernel."""
    global _GEOM_KERN
    if _GEOM_KERN is None:
        _GEOM_KERN = cp.ElementwiseKernel(
            'raw float64 fu, raw float64 fr0, raw float64 cen, raw float64 e1, raw float64 e2, raw float64 en, int32 Pf',
            'float64 ux, float64 uy, float64 uz, float64 wn',
            '''
            const int p = i % Pf; const int b = i / Pf;
            const double wx = fr0[p] * fu[3 * p] - cen[3 * b], wy = fr0[p] * fu[3 * p + 1] - cen[3 * b + 1], wz = fr0[p] * fu[3 * p + 2] - cen[3 * b + 2];
            wn = sqrt(wx * wx + wy * wy + wz * wz);
            ux = (wx * e1[0] + wy * e1[1] + wz * e1[2]) / wn;
            uy = (wx * e2[0] + wy * e2[1] + wz * e2[2]) / wn;
            uz = (wx * en[0] + wy * en[1] + wz * en[2]) / wn;
            ''', 'fastsar_final_geom')
    return _GEOM_KERN


def make_ffbp_cuda(plan, coll, final_mode='fp32', store='fp32', wf=None):
    """Build form(S) -> complex64 image [nx, ny] (device) for the plan and the collection arrays (host float64).
    final_mode: 'fp32' (CUDA cores, float32) or 'f16tc' (tensor cores, float16 operands, float32 accumulation).
    store: 'fp32' or 'f16' for the phase history, every intermediate and the final-stage input in memory; the filter
    arithmetic accumulates in float32 in both cases."""
    kern = _kernels(store)
    levels, T, L = plan['levels'], plan['T'], len(plan['levels'])
    fin = plan['final']
    Pf, Qf = fin['P'], fin['K']
    a0, a1, fc2 = 2.0 * fin['f0'] / C, 2.0 * fin['df'] / C, 2.0 * fin['fc'] / C
    e1, e2 = np.asarray(plan['e1'], np.float64), np.asarray(plan['e2'], np.float64)
    en = np.cross(e1, e2)
    dlx_h = ((np.arange(T) - (T - 1) / 2.0) * plan['spx']).astype(np.float64)
    dly_h = ((np.arange(T) - (T - 1) / 2.0) * plan['spy']).astype(np.float64)
    dlx, dly = cp.asarray(dlx_h, cp.float32), cp.asarray(dly_h, cp.float32)
    dev = []
    for i, (lv, cl) in enumerate(zip(levels, coll['levels'])):
        e = {}
        if i < HOST_LEVELS:
            e['c0'], e['slope'] = cp.asarray(cl['c0'], cp.float32), cp.asarray(cl['slope'], cp.float32)
        else:
            e.update(u=cp.asarray(cl['u']), r0=cp.asarray(cl['r0']), d=cp.asarray(lv['d']), ref=cp.asarray(lv['ref']))
        dev.append(e)
    fu, fr0 = cp.asarray(coll['final']['u']), cp.asarray(coll['final']['r0'])
    fcen = cp.asarray(fin['cen'])
    wfd = None if wf is None else cp.asarray(wf)
    dlxw, dlyw = cp.asarray(dlx_h, cp.float32), cp.asarray(dly_h, cp.float32)
    dlx64, dly64 = cp.asarray(dlx_h), cp.asarray(dly_h)        # uploaded once: a host copy per call waits for the GPU
    dummy_w = cp.zeros(1, cp.float32)
    e1d, e2d, end = cp.asarray(e1), cp.asarray(e2), cp.asarray(en)
    sx0, sy0 = levels[0]['sx'], levels[0]['sy']
    G = sx0 * sy0
    mx, my = plan['Nx'] // sx0, plan['Ny'] // sy0
    shape_g = [s for lv in levels[1:] for s in (lv['sx'], lv['sy'])] + [T, T]
    perm_g = [2 * i for i in range(L - 1)] + [2 * (L - 1)] + [2 * i + 1 for i in range(L - 1)] + [2 * (L - 1) + 1]
    # shared memory per block: 48 KB by default, more when the kernel opts in (99 KB on Ada, 64 KB on Turing)
    smem_max = int(cp.cuda.Device().attributes.get('MaxSharedMemoryPerBlockOptin', 48 * 1024))
    # pulses per table: 2 within 48 KB (every card), more where the card's shared memory allows (FASTSAR_FINAL_PPS)
    pps_env = int(os.environ.get('FASTSAR_FINAL_PPS', 0) or 0)
    pps = pps_env or (2 if 4 * T * (2 * Qf) * 4 <= 48 * 1024 else 1)
    smem_final = 4 * T * (pps * Qf) * 4
    assert T % 4 == 0 and T * T // 8 <= 1024 and (T * T // 8) % (2 * T) == 0, T
    if smem_final > smem_max:
        raise ValueError(f"the cuda final stage's tables ({smem_final // 1024} KB for {Qf} frequency samples per final "
                         f"tile) exceed the GPU's shared memory ({smem_max // 1024} KB): use backend='cpu' or 'jax'")

    cc = cp.cuda.Device().compute_capability
    tc_ver = int(os.environ.get('FASTSAR_TC_KERNEL', 0) or 0) or 2
    if tc_ver == 2 and _tc_smem(2, 1, Qf, False) > _smem_max():
        tc_ver = 1                                              # the double-buffered tables do not fit: the 0.1.2 kernel
    # float32 on the tensor cores as three bfloat16 passes (Ampere and later, T = 32, when the tables fit), the CUDA-core
    # kernel otherwise; FASTSAR_FINAL=fp32 keeps the CUDA cores
    use_tc3 = (final_mode == 'fp32' and T == 32 and int(cc) >= 80 and tc_ver == 2 and _tc_smem(2, 1, Qf, True) <= _smem_max()
               and os.environ.get('FASTSAR_FINAL', 'tc3') == 'tc3')

    def final(are, aim, cen, wts=None):
        """are, aim [B, Pf, Qf]; cen [B, 3] float64; wts None or (w0, gx, gyr) [B, Pf] float32 -> (re, im) [B, T, T]."""
        B = are.shape[0]
        t0 = _tick()
        ux, uy, uz, wn = (cp.empty((B, Pf), cp.float64) for _ in range(4))
        _final_geom_kernel()(fu, fr0, cp.ascontiguousarray(cen, cp.float64), e1d, e2d, end, np.int32(Pf), ux, uy, uz, wn)   # one kernel for the per-pulse unit vectors
        mxv, myv, mzv = ux.mean(1), uy.mean(1), uz.mean(1)
        mn = cp.sqrt(mxv * mxv + myv * myv + mzv * mzv)
        ucx, ucy, rc = mxv / mn, myv / mn, wn.mean(1)
        ore = cp.empty((B, T, T), cp.float32)
        oim = cp.empty((B, T, T), cp.float32)
        _mark('final_geom', t0)
        t0 = _tick()
        mode = final_mode
        if mode == 'fp32' and use_tc3:
            mode = 'bf16x3'                                     # three bfloat16 passes on the tensor cores: float32-class
        if mode in ('f16tc', 'bf16x3'):
            ore, oim = final_tile_tc(cp.ascontiguousarray(are), cp.ascontiguousarray(aim), cp.ascontiguousarray(ux.astype(cp.float32)),
                                     cp.ascontiguousarray(uy.astype(cp.float32)), dlx, dly, a0, a1, T, store=store, split3=mode == 'bf16x3', wts=wts, ver=tc_ver)
        else:
            kern['final_tile']((B,), (T * T // 8,), (cp.ascontiguousarray(are), cp.ascontiguousarray(aim), cp.ascontiguousarray(ux.astype(cp.float32)),
                                                cp.ascontiguousarray(uy.astype(cp.float32)), dlx, dly, ore, oim,
                                                np.int32(Pf), np.int32(Qf), np.int32(T), np.float32(a0), np.float32(a1), np.int32(pps),
                                                *((dummy_w,) * 3 if wts is None else tuple(cp.ascontiguousarray(w, cp.float32) for w in wts)),
                                                np.int32(0 if wts is None else 1)), shared_mem=smem_final)
        _mark('final_tile', t0)
        t0 = _tick()
        dx, dy = dlx64[None, :, None], dly64[None, None, :]
        los = ucx[:, None, None] * dx + ucy[:, None, None] * dy
        qc = (dx * dx + dy * dy - los * los) * (fc2 / (2.0 * rc[:, None, None]))
        ang = ((qc - cp.rint(qc)) * (2 * np.pi)).astype(cp.float32)
        c, s = cp.cos(ang), cp.sin(ang)
        out = ore * c - oim * s, ore * s + oim * c
        _mark('final_corr', t0)
        return out

    def tiles(a, b, gs):
        """Level-0 children gs [n, Po0, Ko0] through the remaining levels together (one launch per level and stage for
        all of them) -> their mx x my blocks [n, mx, my] (re, im)."""
        n = len(gs)
        assert list(gs) == list(range(gs[0], gs[0] + n))
        gi = slice(gs[0], gs[0] + n)                          # contiguous children: slices, no index upload
        for i in range(1, L):
            lv, la = levels[i], dev[i]
            if i < HOST_LEVELS:
                c0 = la['c0'][gi].reshape((-1,) + la['c0'].shape[1:])
                sl = la['slope'][gi].reshape((-1,) + la['slope'].shape[1:])
                a, b = _children(kern, a, b, c0, sl, lv)
            else:
                nb_par = a.shape[0] // n
                refs = la['ref'].reshape(G, nb_par, 3)[gi].reshape(-1, 3)
                t0 = _tick()
                c0, sl = _device_phases(la, refs, lv)
                _mark('device_phases', t0)
                a, b = _children(kern, a, b, c0, sl, lv)
        cen = fcen.reshape(G, -1, 3)[gi].reshape(-1, 3)
        if wfd is not None and wfd.ndim == 3 and (final_mode != 'f16tc' or tc_ver == 2):     # weights in the final kernel
            w = wfd.reshape(3, G, -1, Pf)[:, gi].reshape(3, -1, Pf)
            w0 = w[0]
            big = cp.abs(w0) > 1e-6 * cp.maximum(cp.abs(w0).max(), 1e-30)    # on the device: no wait for the host
            gyr = cp.where(big, w[2] / cp.where(w0 == 0, 1, w0), 0.0)
            re, im = final(a, b, cen, (w0, w[1], gyr))
        elif wfd is not None and wfd.ndim == 3:
            w = wfd.reshape(3, G, -1, Pf)[:, gi].reshape(3, -1, Pf)[..., None]
            re, im = final((a * w[0]).astype(a.dtype), (b * w[0]).astype(b.dtype), cen)
            for k, dl in ((1, dlxw[None, :, None]), (2, dlyw[None, None, :])):
                r_, i_ = final((a * w[k]).astype(a.dtype), (b * w[k]).astype(b.dtype), cen)
                re, im = re + dl * r_, im + dl * i_
        else:
            if wfd is not None:
                w = wfd.reshape(G, -1, Pf)[gi].reshape(-1, Pf)[:, :, None]
                a, b = (a * w).astype(a.dtype), (b * w).astype(b.dtype)
            re, im = final(a, b, cen)
        perm = [0] + [q + 1 for q in perm_g]
        return (re.reshape([n] + shape_g).transpose(perm).reshape(n, mx, my),
                im.reshape([n] + shape_g).transpose(perm).reshape(n, mx, my))

    # level-0 children carried through the later levels together: as many as fit in the free memory at the largest
    # level, per level-0 child its input planes, the range-decimated intermediate of all its input pulses (_children)
    # and the output planes; the deeper levels multiply the children by the earlier levels' C
    def _rest():
        isz, n, worst = 2 * np.dtype(kern['dtype']).itemsize, 1, 1
        for lv in levels[1:]:
            worst = max(worst, n * isz * (lv['P'] * lv['K'] + lv['C'] * (lv['P'] + lv['Po']) * lv['Ko']))
            n *= lv['C']
        return worst
    rest = _rest() if L > 1 else 1

    ox, oy, nx, ny = plan['ox'], plan['oy'], plan['nx'], plan['ny']

    def level0_streamed(S, scale, c0, sl, lv, win=None):
        """The first level from a host phase history S [P, K] too large for the device: pulse blocks (with the
        pulse filter's halo) are uploaded, windowed on the device (win: the pulse [P, 1] and sample [1, K] windows,
        device float32, or None), rotated and range-filtered, and pulse-filtered into their output rows.
        c0, sl [1, ng, P] (device) -> [ng, Po, Ko] planes."""
        P_, K_ = S.shape
        ngc, Po, Ko = c0.shape[1], lv['Po'], lv['Ko']
        Dp = lv['Dp']
        fp = lv['fir_p'] if Dp > 1 else dict(L=1, pl=0, kern=np.ones(1))
        L, pl = fp['L'], fp['pl']
        zre = cp.empty((ngc, Po, Ko), kern['dtype'])
        zim = cp.empty((ngc, Po, Ko), kern['dtype'])
        nb = max(1, (memory.STREAM_PULSES - L) // Dp + 1)                    # output rows per block
        for i0 in range(0, Po, nb):
            i1 = min(Po, i0 + nb)
            p0, p1 = Dp * i0 - pl, Dp * (i1 - 1) - pl + L               # input pulses read by these outputs
            a, b = max(p0, 0), min(p1, P_)
            blk = cp.zeros((p1 - p0, K_), cp.complex64)
            if b > a:
                blk[a - p0:b - p0] = cp.asarray(S[a:b])
                if win is not None:
                    blk[a - p0:b - p0] *= win[0][a:b] * win[1]
            pre = cp.ascontiguousarray((blk.real / scale).astype(kern['dtype']))[None]
            pim = cp.ascontiguousarray((blk.imag / scale).astype(kern['dtype']))[None]
            del blk
            cb = cp.zeros((1, ngc, p1 - p0), cp.float32)
            sb = cp.zeros((1, ngc, p1 - p0), cp.float32)
            if b > a:
                cb[:, :, a - p0:b - p0] = c0[:, :, a:b]
                sb[:, :, a - p0:b - p0] = sl[:, :, a:b]
            # the block's outputs read its rows D j + r (j < i1 - i0); with D = 1 the rows are the outputs
            y = _children(kern, pre, pim, cb, sb, dict(lv, P=p1 - p0, Po=i1 - i0, fir_p=dict(fp, pl=0, n_out=i1 - i0)))
            zre[:, i0:i1], zim[:, i0:i1] = y[0], y[1]
            del pre, pim, y
        return zre, zim

    def form(S, ng=None, batch=None, window=None, check=False):
        """S [P, K] complex64 (host or device, already windowed) -> complex64 image [nx, ny] on the device.
        window: None, or (wp [P], wk [K]) applied here, on the device for a history that is uploaded and on the host
        for one that streams; check: refuse non-finite samples here (ValueError). A host
        history whose device planes exceed memory.STREAM_FRACTION of the free device memory is streamed through the
        first level in pulse blocks (FASTSAR_CUDA_STREAM=1 forces it); a smaller one is uploaded once. ng: first-level
        children per group (default: up to 8, within the memory left after the image and the upload; FASTSAR_CUDA_GROUP
        sets it). batch: first-level children carried through the later levels together (default: as many as fit)."""
        lv0, la0 = levels[0], dev[0]
        isz = 2 * np.dtype(kern['dtype']).itemsize
        planes = isz * S.shape[0] * S.shape[1]                # the history as device planes
        full = cp.empty((plan['Nx'], plan['Ny']), cp.complex64)  # first, so that the sizing below leaves room for it
        free = memory.cuda_free()
        stream = isinstance(S, np.ndarray) and (memory.cuda_streams(planes, free)
                                                or os.environ.get('FASTSAR_CUDA_STREAM') == '1')
        if stream and check:                                # the streamed blocks are checked once here, on the host
            _finite(S, np)
            check = False
        if window is not None:
            wpd, wkd = cp.asarray(window[0], cp.float32)[:, None], cp.asarray(window[1], cp.float32)[None, :]

        def block(i):           # rows i .. i + 4096 of S on the device, windowed and checked
            b = cp.asarray(S[i:i + 4096])
            if window is not None:
                b = b * wpd[i:i + 4096] * wkd
            if check:
                _finite(b, cp, i)
            return b
        scale = 1.0
        scaled = kern['dtype'] != cp.float32          # float16 storage: divided by the first block's peak (_upload_planes)
        if not stream:
            # uploaded in row blocks straight into the planes (no full complex copy on the device)
            pre = cp.empty((1,) + S.shape, kern['dtype'])
            pim = cp.empty((1,) + S.shape, kern['dtype'])
            if isinstance(S, np.ndarray):
                scale = _upload_planes(S, pre[0], pim[0], None if window is None else (wpd, wkd), check, scaled)
            else:                                    # a device history: blocks in place
                if scaled:
                    scale = float(cp.abs(block(0)).max()) or 1.0
                for i in range(0, S.shape[0], 4096):
                    b = block(i)
                    pre[0, i:i + 4096] = (b.real / scale).astype(kern['dtype'])
                    pim[0, i:i + 4096] = (b.imag / scale).astype(kern['dtype'])
                    del b
        elif scaled:                                 # streamed: the first block's peak, on the device
            xp = cp if type(S).__module__.startswith('cupy') else np
            b0 = S[:4096] if xp is cp else cp.asarray(S[:4096])
            scale = float(cp.abs(b0).max()) or 1.0
            del b0
        forced = ng is not None or bool(os.environ.get('FASTSAR_CUDA_GROUP'))
        if ng is None:
            ng = memory._env_number('FASTSAR_CUDA_GROUP', 1) or memory.cuda_group(lv0, S.shape[1], isz, memory.cuda_free(), stream)
        if (stream and os.environ.get('FASTSAR_CUDA_STREAM') != '1') or (ng < min(memory.CUDA_GROUP, G) and not forced):
            how = []
            if stream:
                how.append(f'streams the {memory._gb(planes)} phase history from host memory through the first level')
            if ng < min(memory.CUDA_GROUP, G):
                how.append(f'forms the first level in groups of {memory._nchildren(ng)} instead of {memory.CUDA_GROUP}')
            need = memory.full_speed(plan, S.shape[1], 'cuda', isz)[0]
            memory._warn('cuda: for lack of GPU memory FastSAR ' + ' and '.join(how) + ', which is slower; full speed needs '
                         f'about {memory._gb(need)} of GPU memory, {memory._gb(free + full.nbytes)} is free')
        g0 = 0
        while g0 < G:
            gs = list(range(g0, min(G, g0 + ng)))
            c0 = cp.ascontiguousarray(la0['c0'][0, g0:g0 + len(gs)][None])       # a slice: no index upload
            sl = cp.ascontiguousarray(la0['slope'][0, g0:g0 + len(gs)][None])
            try:
                if stream:
                    A, Bm = level0_streamed(S, scale, c0, sl, lv0, None if window is None else (wpd, wkd))
                else:
                    A, Bm = _children(kern, pre, pim, c0, sl, lv0)                   # [ng, Po, Ko]
            except cp.cuda.memory.OutOfMemoryError:
                if ng == 1:
                    raise
                # the model sized the groups too large for this device: half the group, from this one on
                del c0, sl
                cp.get_default_memory_pool().free_all_blocks()
                ng //= 2
                memory._warn(f'cuda: out of GPU memory in the first level; FastSAR continues in groups of '
                             f'{memory._nchildren(ng)}, which is slower ({memory._gb(memory.cuda_free())} free)')
                continue
            g0 += len(gs)
            # the batch does not set the speed (docs/performance.md): sized with room to spare, halved quietly
            bt = batch or int(max(1, min(len(gs), (0.45 * memory.cuda_free()) // rest)))
            k0 = 0
            while k0 < len(gs):
                sub = gs[k0:k0 + bt]
                try:
                    re, im = tiles(A[k0:k0 + len(sub)], Bm[k0:k0 + len(sub)], sub)
                except cp.cuda.memory.OutOfMemoryError:
                    if bt == 1:
                        raise
                    cp.get_default_memory_pool().free_all_blocks()
                    bt //= 2
                    continue
                k0 += len(sub)
                for k, g in enumerate(sub):
                    x, y = g // sy0, g % sy0
                    full[x * mx:(x + 1) * mx, y * my:(y + 1) * my] = re[k] + 1j * im[k]
            del A, Bm
        return full[ox:ox + nx, oy:oy + ny] if scale == 1.0 else full[ox:ox + nx, oy:oy + ny] * np.float32(scale)

    return form


def _finite(S, xp, first=0):
    """Refuse non-finite samples in S (numpy or cupy), checked by sums over blocks of rows; first: the pulse index of
    S's first row in the history, for the message."""
    for i in range(0, S.shape[0], 4096):
        if not np.isfinite(complex(S[i:i + 4096].sum())):
            bad = i + int(xp.argmax((~xp.isfinite(S[i:i + 4096])).any(1)))
            raise ValueError(f'phase history has non-finite samples (NaN or inf), the first in pulse {first + bad}; '
                             'zero them (S[~np.isfinite(S)] = 0) or drop the pulses')


